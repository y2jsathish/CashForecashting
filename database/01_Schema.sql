IF OBJECT_ID('dbo.AtmMaster', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.AtmMaster
    (
        Id                 INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AtmMaster PRIMARY KEY,
        AtmCode            NVARCHAR(20)    NOT NULL,
        AtmName            NVARCHAR(150)   NOT NULL,
        TerminalId         NVARCHAR(30)    NOT NULL,
        RegionId           INT             NOT NULL CONSTRAINT FK_AtmMaster_Regions REFERENCES dbo.Regions(Id),
        BranchId           INT             NOT NULL CONSTRAINT FK_AtmMaster_Branches REFERENCES dbo.Branches(Id),
        Latitude           DECIMAL(9,6)    NOT NULL,
        Longitude          DECIMAL(9,6)    NOT NULL,
        AtmType            TINYINT         NOT NULL, -- 1 OnSite,2 OffSite,3 ThroughTheWall,4 MobileAtm,5 CashRecycler
        Currency           CHAR(3)         NOT NULL,
        Capacity           DECIMAL(18,2)   NOT NULL CONSTRAINT CK_AtmMaster_Capacity CHECK (Capacity >= 0),
        SafetyBufferAmount DECIMAL(18,2)   NOT NULL CONSTRAINT CK_AtmMaster_SafetyBuffer CHECK (SafetyBufferAmount >= 0),
        [Status]           TINYINT         NOT NULL, -- 1 Active,2 Inactive,3 Offline,4 UnderMaintenance,5 Decommissioned
        InstalledDate      DATE            NULL,
        DecommissionedDate DATE            NULL,
        CreatedAtUtc       DATETIME2       NOT NULL CONSTRAINT DF_AtmMaster_CreatedAtUtc DEFAULT (SYSUTCDATETIME()),
        CreatedBy          NVARCHAR(450)   NULL,
        ModifiedAtUtc      DATETIME2       NULL,
        ModifiedBy         NVARCHAR(450)   NULL,
        IsDeleted          BIT             NOT NULL CONSTRAINT DF_AtmMaster_IsDeleted DEFAULT (0),
        CONSTRAINT UQ_AtmMaster_AtmCode UNIQUE (AtmCode),
        CONSTRAINT UQ_AtmMaster_TerminalId UNIQUE (TerminalId)
    );
    CREATE INDEX IX_AtmMaster_Region_Branch ON dbo.AtmMaster(RegionId, BranchId);
    CREATE INDEX IX_AtmMaster_Status ON dbo.AtmMaster([Status]);
END
GO

