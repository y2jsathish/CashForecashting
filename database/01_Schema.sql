        DepositAmount     DECIMAL(18,2)  NOT NULL CONSTRAINT CK_AtmTransactions_DepositAmount CHECK (DepositAmount >= 0),
        RemainingCash     DECIMAL(18,2)  NOT NULL CONSTRAINT CK_AtmTransactions_RemainingCash CHECK (RemainingCash >= 0),
        CashLoaded        DECIMAL(18,2)  NOT NULL CONSTRAINT CK_AtmTransactions_CashLoaded CHECK (CashLoaded >= 0),
        [Source]          TINYINT        NOT NULL, -- 1 CsvUpload,2 ExcelUpload,3 ApiIntegration,4 ScheduledImport
        ValidationStatus  TINYINT        NOT NULL CONSTRAINT DF_AtmTransactions_ValidationStatus DEFAULT (1),
        ValidationNotes   NVARCHAR(500)  NULL,
        ImportBatchId     UNIQUEIDENTIFIER NOT NULL,
        CreatedAtUtc      DATETIME2      NOT NULL CONSTRAINT DF_AtmTransactions_CreatedAtUtc DEFAULT (SYSUTCDATETIME()),
        CreatedBy         NVARCHAR(450)  NULL,
        ModifiedAtUtc     DATETIME2      NULL,
        ModifiedBy        NVARCHAR(450)  NULL,
        IsDeleted         BIT            NOT NULL CONSTRAINT DF_AtmTransactions_IsDeleted DEFAULT (0),
        CONSTRAINT UQ_AtmTransactions_Atm_Date UNIQUE (AtmId, TransactionDate)
    );
    CREATE INDEX IX_AtmTransactions_ImportBatchId ON dbo.AtmTransactions(ImportBatchId);
    CREATE INDEX IX_AtmTransactions_Atm_Date ON dbo.AtmTransactions(AtmId, TransactionDate DESC);
END
