/*
    ATM Cash Forecasting & Replenishment Management System
    01_Schema.sql — SQL Server schema for the domain tables.

    Notes:
    - Users / Roles / UserRoles / UserClaims / RoleClaims / UserLogins / UserTokens are owned by
      ASP.NET Core Identity (AspNetUsers, AspNetRoles, ...) and are generated by EF Core migrations
      (`dotnet ef migrations add InitialCreate` against ATMCashForecasting.Infrastructure). They are
      not hand-scripted here to avoid drifting from the Identity schema version in use.
    - This script is idempotent (CREATE TABLE ... guarded by OBJECT_ID checks) so it can be re-run
      safely against an existing database.
    - Run 02_StoredProcedures.sql, 03_Views.sql and 04_SeedData.sql after this script.
*/

SET NOCOUNT ON;
GO

IF NOT EXISTS (SELECT 1 FROM sys.databases WHERE name = 'AtmCashForecasting')
BEGIN
    PRINT 'Run this script against an existing AtmCashForecasting database (create it via `dotnet ef database update` or CREATE DATABASE first).';
END
GO

-- =========================================================================================
-- Fine-grained module-level permissions, bridged to AspNetRoles (Module 1: RBAC).
-- =========================================================================================
IF OBJECT_ID('dbo.Permissions', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.Permissions
    (
        Id          INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Permissions PRIMARY KEY,
        [Name]      NVARCHAR(100)     NOT NULL,
        [Module]    NVARCHAR(100)     NOT NULL,
        Description NVARCHAR(300)     NULL,
        CONSTRAINT UQ_Permissions_Name UNIQUE ([Name])
    );
END
GO

IF OBJECT_ID('dbo.RolePermissions', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.RolePermissions
    (
        RoleId       INT NOT NULL,           -- FK to AspNetRoles.Id (added once Identity tables exist)
        PermissionId INT NOT NULL CONSTRAINT FK_RolePermissions_Permissions REFERENCES dbo.Permissions(Id),
        CONSTRAINT PK_RolePermissions PRIMARY KEY (RoleId, PermissionId)
    );
