    CREATE TABLE dbo.AtmTransactions
    (
        Id                INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AtmTransactions PRIMARY KEY,
        AtmId             INT            NOT NULL CONSTRAINT FK_AtmTransactions_AtmMaster REFERENCES dbo.AtmMaster(Id),
        TransactionDate   DATE           NOT NULL,
