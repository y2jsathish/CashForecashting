IF OBJECT_ID('dbo.ForecastResults', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.ForecastResults
    (
        Id                          INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ForecastResults PRIMARY KEY,
        AtmId                       INT            NOT NULL CONSTRAINT FK_ForecastResults_AtmMaster REFERENCES dbo.AtmMaster(Id),
        ForecastRunId               UNIQUEIDENTIFIER NOT NULL,
        RunAtUtc                    DATETIME2      NOT NULL,
        Method                      TINYINT        NOT NULL, -- 1 MA,2 WMA,3 Trend,4 Seasonal,5 MLNet,6 Prophet,7 XGBoost,8 LSTM
