IF OBJECT_ID('dbo.ReplenishmentRecommendations', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.ReplenishmentRecommendations
    (
        Id                    INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ReplenishmentRecommendations PRIMARY KEY,
        AtmId                 INT           NOT NULL CONSTRAINT FK_ReplRec_AtmMaster REFERENCES dbo.AtmMaster(Id),
        ForecastResultId      INT           NOT NULL CONSTRAINT FK_ReplRec_ForecastResults REFERENCES dbo.ForecastResults(Id),
        GeneratedAtUtc        DATETIME2     NOT NULL CONSTRAINT DF_ReplRec_GeneratedAtUtc DEFAULT (SYSUTCDATETIME()),
