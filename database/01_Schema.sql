        RecommendedLoadAmount DECIMAL(18,2) NOT NULL CONSTRAINT CK_ReplRec_LoadNonNegative CHECK (RecommendedLoadAmount >= 0),
        Priority              TINYINT       NOT NULL, -- 1 Routine,2 Scheduled,3 Urgent,4 Emergency
