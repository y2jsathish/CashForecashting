        RiskLevel             TINYINT       NOT NULL, -- 1 Low,2 Medium,3 High,4 Critical
        IsFulfilled           BIT           NOT NULL CONSTRAINT DF_ReplRec_IsFulfilled DEFAULT (0),
        FulfilledByCashLoadId INT           NULL,
        CreatedAtUtc          DATETIME2     NOT NULL CONSTRAINT DF_ReplRec_CreatedAtUtc DEFAULT (SYSUTCDATETIME()),
        IsDeleted             BIT           NOT NULL CONSTRAINT DF_ReplRec_IsDeleted DEFAULT (0)
    );
    CREATE INDEX IX_ReplRec_Atm_Fulfilled ON dbo.ReplenishmentRecommendations(AtmId, IsFulfilled);
